import { parseAlg } from "./metrics";
import type { TrainerCaseData } from "./types";

/**
 * The algorithm review written to docs/algs-review.md (review-algs.test.ts renders it and
 * checks the committed file): length and score distributions per set, cases whose main
 * algorithm is more than three turns longer than the proven shortest in all six faces,
 * cases whose listed algorithms are near copies of each other, and algorithms with an
 * awkward stretch by our score. Pure: it reads the shipped data and the search's results.
 */

export type Optimum = {
  /** The main algorithm's length in the half-turn metric. */
  main: number;
  /** The proven shortest, or null when the search stopped first. */
  optimum: number | null;
  /** Every length below this is proven to have no solution. */
  atLeast: number;
  optimal: string | null;
};

export type ReviewedSet = {
  id: string;
  title: string;
  cases: readonly TrainerCaseData[];
  optimum: Readonly<Record<string, Optimum>>;
  /** How the optimum was found, in a sentence. */
  how: string;
};

/** Turns as written, half turns and primes kept apart, rotations dropped. */
const tokens = (alg: string) =>
  alg.split(/\s+/).filter((t) => t && !/^[xyz]/.test(t));

/** Edit distance between two algorithms, turn by turn. */
export function turnDistance(a: string, b: string): number {
  const x = tokens(a);
  const y = tokens(b);
  const row = Array.from({ length: y.length + 1 }, (_, j) => j);
  for (let i = 1; i <= x.length; i++) {
    let diagonal = row[0] as number;
    row[0] = i;
    for (let j = 1; j <= y.length; j++) {
      const up = row[j] as number;
      row[j] = Math.min(
        up + 1,
        (row[j - 1] as number) + 1,
        diagonal + (x[i - 1] === y[j - 1] ? 0 : 1),
      );
      diagonal = up;
    }
  }
  return row[y.length] as number;
}

/** Two algorithms differ in at most two turns (one changed, added or dropped each). */
export const nearCopies = (a: string, b: string) => turnDistance(a, b) <= 2;

/**
 * An awkward stretch by the score's own terms: three grip changes in a row (three non-U
 * turns in a row, each on another face family than the one before), or a rotation.
 */
export function awkward(alg: string): string | null {
  const FAMILY: Record<string, string> = {
    R: "R",
    r: "R",
    M: "R",
    L: "L",
    l: "L",
    F: "F",
    f: "F",
    S: "F",
    B: "B",
    b: "B",
    D: "D",
    d: "D",
    E: "D",
  };
  let run = 0;
  let family: string | null = null;
  for (const t of parseAlg(alg)) {
    if ("xyz".includes(t.letter)) return "a rotation";
    const next = FAMILY[t.letter];
    if (!next) continue;
    if (family !== null && next !== family) {
      run++;
      if (run >= 3) return "three grip changes in a row";
    } else if (family !== null) run = 0;
    family = next;
  }
  return null;
}

function spread(values: readonly number[]): string {
  const sorted = [...values].sort((a, b) => a - b);
  const at = (q: number) =>
    sorted[Math.min(sorted.length - 1, Math.floor(q * sorted.length))];
  const mean = values.reduce((a, b) => a + b, 0) / values.length;
  return `${sorted[0]} / ${at(0.5)} / ${sorted[sorted.length - 1]} (mean ${mean.toFixed(1)})`;
}

function histogram(values: readonly number[]): string {
  const counts = new Map<number, number>();
  for (const v of values) counts.set(v, (counts.get(v) ?? 0) + 1);
  return [...counts.entries()]
    .sort((a, b) => a[0] - b[0])
    .map(([v, n]) => `${v}: ${n}`)
    .join(", ");
}

export function renderReview(
  sets: readonly ReviewedSet[],
  notes: readonly string[],
): string {
  const out: string[] = [
    "# Algorithm review",
    "",
    "Generated by `packages/algs/src/review-algs.test.ts` (`ALGS_WRITE=1`) from the shipped data and `packages/algs/src/candidates/review-search.json`. Do not edit.",
    "",
    "Lengths are in the half-turn metric (a face or wide turn is one, a slice two, a rotation none); the score is `metrics.ts`'s. The shortest is our own search's in R U F L D B with no rotations (`optimal.ts`), U turns before and after free.",
    "",
    ...notes.map((n) => `- ${n}`),
    "",
  ];
  const flagged: string[] = [];
  const copies: string[] = [];
  const awkwards: string[] = [];
  out.push(
    "## Distributions",
    "",
    "| Set | Cases | Main length min / median / max | Main score min / median / max | Main lengths | Unproven optimum |",
    "|---|---|---|---|---|---|",
  );
  for (const s of sets) {
    const lengths = s.cases.map((c) => s.optimum[c.id]?.main ?? 0);
    const scores = s.cases.map((c) => c.algs[0]?.metrics.score ?? 0);
    const unproven = s.cases.filter((c) => s.optimum[c.id]?.optimum === null);
    out.push(
      `| ${s.title} | ${s.cases.length} | ${spread(lengths)} | ${spread(scores)} | ${histogram(lengths)} | ${unproven.length} |`,
    );
    for (const c of s.cases) {
      const o = s.optimum[c.id];
      const main = c.algs[0];
      if (!o || !main) continue;
      const gap = o.optimum !== null ? o.main - o.optimum : o.main - o.atLeast;
      // More than three longer: proven when the optimum is known, or when every length up
      // to three below the main one was searched in vain is it proven not to be.
      if (o.optimum !== null && gap > 3)
        flagged.push(
          `| ${s.title} | ${c.label} | \`${main.moves}\` | ${o.main} | ${o.optimum} | \`${o.optimal}\` |`,
        );
      if (o.optimum === null && o.atLeast < o.main - 3)
        flagged.push(
          `| ${s.title} | ${c.label} | \`${main.moves}\` | ${o.main} | ≥ ${o.atLeast} (search stopped) | |`,
        );
      if (
        c.algs.length >= 2 &&
        c.algs.every((a, i) =>
          c.algs.every((b, j) => j <= i || nearCopies(a.moves, b.moves)),
        )
      )
        copies.push(
          `| ${s.title} | ${c.label} | ${c.algs.map((a) => `\`${a.moves}\``).join("<br>")} |`,
        );
      for (const a of c.algs) {
        const why = awkward(a.moves);
        if (why)
          awkwards.push(
            `| ${s.title} | ${c.label} | \`${a.moves}\` | ${why} |`,
          );
      }
    }
  }
  out.push("", "How each set's shortest was found:", "");
  for (const s of sets) out.push(`- ${s.title}: ${s.how}`);
  out.push(
    "",
    "## Main algorithm more than three turns longer than the shortest",
    "",
    flagged.length === 0
      ? "None."
      : "| Set | Case | Main | Length | Shortest | A shortest |",
  );
  if (flagged.length > 0) out.push("|---|---|---|---|---|---|", ...flagged);
  out.push(
    "",
    "## Every listed algorithm a near copy of the others",
    "",
    "Near copy: at most two turns changed, added or dropped between any two.",
    "",
    copies.length === 0 ? "None." : "| Set | Case | Algorithms |",
  );
  if (copies.length > 0) out.push("|---|---|---|", ...copies);
  out.push(
    "",
    "## Awkward stretches",
    "",
    "Three grip changes in a row (three non-U turns, each on another face family than the one before), or a rotation.",
    "",
    awkwards.length === 0 ? "None." : "| Set | Case | Algorithm | What |",
  );
  if (awkwards.length > 0) out.push("|---|---|---|---|", ...awkwards);
  out.push("");
  return out.join("\n");
}
